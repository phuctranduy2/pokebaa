function mergeSetCards(curated: PokemonCard[], fullPool: PokemonCard[], setId: string): PokemonCard[] {
  const seen = new Set<string>();
  const result: PokemonCard[] = [];
  for (const c of curated) {
    if (!seen.has(c.id)) {
      seen.add(c.id);
      if (!c.setId) c.setId = setId;
      result.push(c);
    }
  }
  for (const c of fullPool) {
    if (!seen.has(c.id)) {
      seen.add(c.id);
      if (!c.setId) c.setId = setId;
      result.push(c);
    }
  }
  return result;
}

